#[cfg(test)]
mod tests {

    use zench::bench;
    use zench::bx;

    fn fibonacci(n: u64) -> u64 {
        match n {
            0 => 1,
            1 => 1,
            n => fibonacci(n - 1) + fibonacci(n - 2),
        }
    }

    #[test]
    fn bench_fibs() {
        let mut b = bench!();

        for case in [10, 20, 30] {
            b.bench(case, || {
                fibonacci(bx(case));
            });
        }
    }
}

