#[cfg(test)]
mod tests {

    use zench::bench;
    use zench::bx;

    fn fibonacci(n: u64) -> u64 {
        match n {
            0 => 1,
            1 => 1,
            n => fibonacci(n - 1) + fibonacci(n - 2),
        }
    }

    #[test]
    fn bench_fibs() {
        bench!(
            "fib 10" => fibonacci(bx(10)),
            "fib 20" => fibonacci(bx(20)),
            "fib 30" => fibonacci(bx(30)),
        );
    }
}

